# курсу з певної теми для цільової айдиторії(початківці,
# професіонали, діти, тощо).
# Вхідні параметри: тема, опис цільової аудиторії
# Реалізуйте двома способами:
#  Zero-shot
#  Few-shot
from langchain_core.prompts import PromptTemplate
from langchain_google_genai import GoogleGenerativeAI
from langchain.prompts import PromptTemplate

import dotenv
import os


dotenv.load_dotenv()


api_key = os.getenv('GEMINI_API_KEY')

llm = GoogleGenerativeAI(
    model='gemini-2.0-flash',  # назва моделі
    google_api_key=api_key,  # ваша API
)

auditory = input("Для кого Ви хочете курс? (наприклад: початківці, професіонали, діти, тощо):  ")

# Створення шаблону промпта #  Zero-shot
prompt = PromptTemplate.from_template(
    """
    Ти — асистент зі створення навчального плану. Створи детальний план навчального курсу з англійської мови для {auditory}.

    **Вимоги до результату:**
    1. Назва курсу.
    2. Короткий опис курсу (2–3 речення).
    3. Цілі та результати навчання (що зможе робити студент після завершення курсу).
    4. Структура курсу: розбий на модулі (наприклад, 6–8), кожен модуль має включати:
       - Назву модуля
       - Короткий опис
       - Теми занять
       - Ключову лексику
       - Основні граматичні конструкції
    5. Типи активностей: вкажи, які вправи використовуються (аудіювання, читання, говоріння, рольові ігри, словникові ігри тощо).
    6. Формат курсу: онлайн чи офлайн, груповий чи індивідуальний (опціонально).

    Напиши результат українською мовою.
    """
)

chain = prompt | llm

response = chain.invoke({'auditory': auditory})
print(response)
